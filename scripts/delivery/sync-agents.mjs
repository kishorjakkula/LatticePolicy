#!/usr/bin/env node
// Generates each AI tool's instruction files from the canonical contracts in
// agents/. Run `npm run agents:sync`; CI runs it with --check and fails on drift.
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { loadAgents, repoRoot } from './lib.mjs'

const START = '<!-- delivery-flow:start (generated by npm run agents:sync from agents/; do not edit here) -->'
const END = '<!-- delivery-flow:end -->'
const BANNER = 'Generated by `npm run agents:sync` from `agents/`. Edit the files in `agents/` instead.'

function agentTable(agents) {
  return [
    '| Stage | Agent | Contract | Writes |',
    '| --- | --- | --- | --- |',
    ...agents.map((agent) => `| ${agent.stage} | ${agent.name} | \`${agent.file}\` | \`${agent.writes}\` |`),
  ].join('\n')
}

function flowSummary(agents) {
  return [
    '## Delivery flow',
    '',
    'Every coding request follows the delivery flow in `docs/delivery/WORKFLOW.md`,',
    'whichever AI assistant does the work. Start with',
    '`Start the LatticePolicy delivery flow for: <request>` or',
    '`npm run flow -- start "<request>"`, then run each agent in order',
    '(`npm run flow -- next <WP>` prints its prompt). Agents may branch, commit and',
    'open pull requests between gates; they stop at every human gate (A requirements,',
    'B design, C merge, D business sign-off), never approve a gate themselves, never',
    'merge, and never deploy to production. The code reviewer runs in a separate',
    'session from the developer. Quick changes use the quick track; anything touching',
    'tenancy, authentication, rating, filed forms, customer data, migrations or AI is major.',
    '',
    agentTable(agents),
    '',
    'Domain and engineering knowledge: `docs/knowledge/` (check each file\'s',
    '`last_reviewed`). Pull requests state `Work package: WP-NNNN` or',
    '`Delivery track: quick — <reason>`.',
  ].join('\n')
}

/** Every generated file, as { path: content }. */
export function renderAdapters(root) {
  const agents = loadAgents(root)
  const files = {}
  const summary = flowSummary(agents)

  for (const agent of agents) {
    files[`.claude/agents/${agent.id}.md`] = [
      '---',
      `name: ${agent.id}`,
      `description: ${JSON.stringify(agent.summary)}`,
      '---',
      '',
      `<!-- ${BANNER} -->`,
      '',
      agent.body,
      '',
      'Work-package mechanics: `docs/delivery/WORKFLOW.md` and `npm run flow -- help`.',
      '',
    ].join('\n')
    files[`.github/prompts/${agent.id}.prompt.md`] = [
      '---',
      'mode: agent',
      `description: ${JSON.stringify(agent.summary)}`,
      '---',
      '',
      `<!-- ${BANNER} -->`,
      '',
      agent.body,
      '',
    ].join('\n')
  }

  files['.github/copilot-instructions.md'] = [
    `<!-- ${BANNER} -->`,
    '',
    '# LatticePolicy instructions for GitHub Copilot',
    '',
    'Read `AGENTS.md` first: it holds the project orientation and safety rules every',
    'contributor follows. Agent role prompts are in `.github/prompts/`.',
    '',
    summary,
    '',
  ].join('\n')

  files['.cursor/rules/delivery-flow.mdc'] = [
    '---',
    'description: LatticePolicy delivery flow and agent roles for any coding request',
    'globs:',
    'alwaysApply: true',
    '---',
    '',
    `<!-- ${BANNER} -->`,
    '',
    'Read `AGENTS.md` for project orientation and safety rules.',
    '',
    summary,
    '',
  ].join('\n')

  for (const name of ['CLAUDE.md', 'GEMINI.md']) {
    files[name] = [
      `<!-- ${BANNER} -->`,
      '',
      `# LatticePolicy`,
      '',
      'Read `AGENTS.md` first. It is the single source of project orientation and',
      'safety rules for every AI assistant; this file only points to it.',
      '',
      summary,
      '',
      name === 'CLAUDE.md' ? 'Each role is also available as a Claude Code sub-agent in `.claude/agents/`.\n' : '',
    ].join('\n')
  }

  const agentsMd = fs.readFileSync(path.join(root, 'AGENTS.md'), 'utf8')
  const block = `${START}\n${summary}\n${END}`
  files['AGENTS.md'] = agentsMd.includes(START)
    ? agentsMd.replace(new RegExp(`${escape(START)}[\\s\\S]*?${escape(END)}`), () => block)
    : agentsMd.replace(/\n## Repository Shape/, () => `\n${block}\n\n## Repository Shape`)
  if (!files['AGENTS.md'].includes(START)) files['AGENTS.md'] = `${agentsMd.trimEnd()}\n\n${block}\n`
  return files
}

function escape(text) {
  return text.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
}

/** Generated files left behind after their contract was removed. */
function orphans(root, files) {
  const found = []
  for (const dir of ['.claude/agents', '.github/prompts']) {
    const full = path.join(root, dir)
    if (!fs.existsSync(full)) continue
    for (const name of fs.readdirSync(full)) {
      const rel = `${dir}/${name}`
      if (!files[rel] && fs.readFileSync(path.join(full, name), 'utf8').includes(BANNER)) found.push(rel)
    }
  }
  return found
}

/** Files whose content differs from what would be generated, or that should no longer exist. */
export function drift(root) {
  const files = renderAdapters(root)
  const changed = Object.entries(files)
    .filter(([file, content]) => {
      const full = path.join(root, file)
      return !fs.existsSync(full) || fs.readFileSync(full, 'utf8') !== content
    })
    .map(([file]) => file)
  return [...changed, ...orphans(root, files)]
}

export function writeAdapters(root) {
  const files = renderAdapters(root)
  // Remove generated agent files whose contract no longer exists.
  for (const rel of orphans(root, files)) fs.unlinkSync(path.join(root, rel))
  for (const [file, content] of Object.entries(files)) {
    fs.mkdirSync(path.dirname(path.join(root, file)), { recursive: true })
    fs.writeFileSync(path.join(root, file), content)
  }
  return Object.keys(files)
}

/** True when this file is the script being run (works with spaces, symlinks and Windows paths). */
function isMain() {
  if (!process.argv[1]) return false
  try {
    return fs.realpathSync(fileURLToPath(import.meta.url)) === fs.realpathSync(path.resolve(process.argv[1]))
  } catch {
    return false
  }
}

if (isMain()) {
  try {
    const root = repoRoot()
    if (process.argv.includes('--check')) {
      const stale = drift(root)
      if (stale.length) {
        console.error(`Agent files are out of date; run npm run agents:sync:\n- ${stale.join('\n- ')}`)
        process.exitCode = 1
      } else console.log('Agent files are in sync with agents/.')
    } else {
      const written = writeAdapters(root)
      console.log(`Wrote ${written.length} files from agents/.`)
    }
  } catch (error) {
    console.error(error.message)
    process.exitCode = 1
  }
}
